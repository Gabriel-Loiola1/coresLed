/**
 * Escreve os dados aplicando escala global de brilho e correção gama matemática.
 */
void npWrite() {
  for (uint i = 0; i < LED_COUNT; ++i) {
    // 1. Aplica o nível de brilho
    // 2. Passa o resultado pela tabela Gamma para corrigir a percepção visual
    uint8_t g = gamma8[(leds[i].G * global_brightness) / 255];
    uint8_t r = gamma8[(leds[i].R * global_brightness) / 255];
    uint8_t b = gamma8[(leds[i].B * global_brightness) / 255];

    pio_sm_put_blocking(np_pio, sm, g);
    pio_sm_put_blocking(np_pio, sm, r);
    pio_sm_put_blocking(np_pio, sm, b);
  }
  sleep_us(100); 
}